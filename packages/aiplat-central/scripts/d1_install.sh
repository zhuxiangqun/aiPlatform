#!/usr/bin/env bash
# aiPlat Central D1 install — materialize host layout under $AIPLAT_HOME/central.
# Does NOT start PG/HA. Optional --smoke runs healthz contract check.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=d1_lib.sh
source "$SCRIPT_DIR/d1_lib.sh"

SMOKE=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --smoke) SMOKE=1; shift ;;
    -h|--help)
      echo "Usage: $0 [--smoke]"
      echo "  Installs Central Thin under \${AIPLAT_CENTRAL_PREFIX:-\$AIPLAT_HOME/central}"
      exit 0
      ;;
    *) echo "Unknown arg: $1" >&2; exit 2 ;;
  esac
done

d1_require_python
PREFIX="$(d1_prefix)"
VER="$(d1_pkg_version)"
VER_DIR="$PREFIX/versions/$VER"
mkdir -p "$PREFIX/versions" "$PREFIX/backups" "$PREFIX/logs"

echo "aiPlat Central D1 install → $VER_DIR (version=$VER)"
d1_materialize_version "$VER_DIR"
ln -sfn "versions/$VER" "$PREFIX/current"

ENV_FILE="$PREFIX/env"
if [[ ! -f "$ENV_FILE" ]]; then
  cat >"$ENV_FILE" <<EOF
# Central D1 Thin env — generated by d1_install.sh
AIPLAT_CORE_HOST=127.0.0.1
AIPLAT_CORE_PORT=8002
# Optional isolate:
# AIPLAT_HOME=$PREFIX/runtime-home
EOF
  echo "Wrote $ENV_FILE"
else
  echo "Keep existing $ENV_FILE"
fi

mkdir -p "$PREFIX/bin"
cat >"$PREFIX/bin/aiplat-core-healthz" <<EOF
#!/usr/bin/env bash
set -euo pipefail
PREFIX="$PREFIX"
set -a
# shellcheck disable=SC1090
source "\$PREFIX/env"
set +a
HOST="\${AIPLAT_CORE_HOST:-127.0.0.1}"
PORT="\${AIPLAT_CORE_PORT:-8002}"
curl -fsS "http://\${HOST}:\${PORT}/api/core/healthz"
EOF
chmod +x "$PREFIX/bin/aiplat-core-healthz"

cat >"$PREFIX/INSTALL_META.json" <<EOF
{"capability_id":"aiplat","product_id":"aiplat","deploy_unit":"central","version":"$VER","prefix":"$PREFIX","installed_at":"$(date -u +%Y-%m-%dT%H:%M:%SZ)","thin":true,"pg_ha":false}
EOF

echo "OK installed Central Thin → $PREFIX/current"
if [[ "$SMOKE" -eq 1 ]]; then
  bash "$SCRIPT_DIR/d1_smoke.sh"
fi
