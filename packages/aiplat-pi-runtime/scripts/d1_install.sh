#!/usr/bin/env bash
# Pi D1 install — materialize Thin runtime under $AIPLAT_HOME/pi (or AIPLAT_PI_PREFIX).
# Does NOT start control plane. Reuses Gate3 Thin path (ADR-08). Optional --smoke.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=d1_lib.sh
source "$SCRIPT_DIR/d1_lib.sh"

SMOKE=0
APP_HOME=""
while [[ $# -gt 0 ]]; do
  case "$1" in
    --smoke) SMOKE=1; shift ;;
    --app-home) APP_HOME="$2"; shift 2 ;;
    -h|--help)
      echo "Usage: $0 [--smoke] [--app-home DIR]"
      echo "  Installs Pi Thin under \${AIPLAT_PI_PREFIX:-\$AIPLAT_HOME/pi}"
      exit 0
      ;;
    *) echo "Unknown arg: $1" >&2; exit 2 ;;
  esac
done

d1_require_node
PREFIX="$(d1_prefix)"
VER="$(d1_pkg_version)"
VER_DIR="$PREFIX/versions/$VER"
mkdir -p "$PREFIX/versions" "$PREFIX/bundles" "$PREFIX/backups" "$PREFIX/logs"

echo "Pi D1 install → $VER_DIR (version=$VER)"
d1_materialize_version "$VER_DIR"

# current → this version
ln -sfn "versions/$VER" "$PREFIX/current"

# default app bundle: sample-app unless --app-home
if [[ -n "$APP_HOME" ]]; then
  if [[ ! -f "$APP_HOME/agent_manifest.json" ]]; then
    echo "ERROR: --app-home missing agent_manifest.json: $APP_HOME" >&2
    exit 3
  fi
  ln -sfn "$(cd "$APP_HOME" && pwd)" "$PREFIX/bundles/current"
else
  SAMPLE="$(d1_repo_pkg)/fixtures/sample-app"
  ln -sfn "$SAMPLE" "$PREFIX/bundles/current"
fi

ENV_FILE="$PREFIX/env"
if [[ ! -f "$ENV_FILE" ]]; then
  cat >"$ENV_FILE" <<EOF
# Pi D1 Thin env — generated by d1_install.sh (do not reuse control-plane secrets)
AIPLAT_HTTP_STUB=1
AIPLAT_HTTP_PORT=18787
AIPLAT_HTTP_HOST=127.0.0.1
AIPLAT_HTTP_API_KEY=pi-d1-local-key
AIPLAT_APP_HOME=$PREFIX/bundles/current
# Keep enterprise off for Thin (Gate3)
AIPLAT_ENTERPRISE=0
EOF
  echo "Wrote $ENV_FILE"
else
  echo "Keep existing $ENV_FILE"
fi

# Convenience wrappers
mkdir -p "$PREFIX/bin"
cat >"$PREFIX/bin/aiplat-http" <<EOF
#!/usr/bin/env bash
set -euo pipefail
PREFIX="$PREFIX"
set -a
# shellcheck disable=SC1090
source "\$PREFIX/env"
set +a
exec node "\$PREFIX/current/bin/aiplat-http.mjs" "\$@"
EOF
chmod +x "$PREFIX/bin/aiplat-http"

cat >"$PREFIX/INSTALL_META.json" <<EOF
{"capability_id":"pi","version":"$VER","prefix":"$PREFIX","installed_at":"$(date -u +%Y-%m-%dT%H:%M:%SZ)","thin":true,"adr":"ADR-08/Gate3"}
EOF

echo "PASS: Pi D1 install prefix=$PREFIX current → versions/$VER"

if [[ "$SMOKE" == "1" ]]; then
  bash "$SCRIPT_DIR/d1_smoke.sh"
fi
