"""
Evaluator Workbench (P1)

Goal:
- Standardize evaluator report schema (JSON)
- Apply threshold gate (pass/fail)
- Persist as LearningArtifact + run_events for observability

This module is intentionally LLM-agnostic: it accepts a report JSON payload
generated by any evaluator agent (human/LLM/Playwright).

Scoring dimensions are configurable via PipelineStageConfig.scoring_dimensions
or AIPLAT_EVAL_DIMENSIONS env var. Per CLAUDE.md §5.29.
"""

from __future__ import annotations
import logging

import os
import time
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Tuple

from core.learning.manager import LearningManager
from core.learning.types import LearningArtifactKind
from .dimensions import get_scoring_dimensions, get_dimension_names, get_dimension_thresholds


@dataclass
class EvaluatorThresholds:
    """Thresholds per dimension, keyed by dimension name."""
    thresholds: Dict[str, float] = field(default_factory=dict)

    @classmethod
    def from_dimensions(cls, dims: Optional[List[Dict[str, Any]]] = None) -> "EvaluatorThresholds":
        thresh = get_dimension_thresholds(dims)
        return cls(thresholds=thresh)

    @classmethod
    def from_dict(cls, d: Optional[Dict[str, Any]]) -> "EvaluatorThresholds":
        """Deserialize from dict. Keys ending in _min are threshold entries."""
        dd = d or {}
        thresholds: Dict[str, float] = {}
        for key, val in dd.items():
            if key.endswith("_min"):
                thresholds[key.replace("_min", "")] = float(val)
        return cls(thresholds=thresholds)

    def to_dict(self) -> Dict[str, Any]:
        return {f"{k}_min": v for k, v in self.thresholds.items()}


def _get_score(report: Dict[str, Any], key: str) -> float:
    score = (report.get("score") or {}) if isinstance(report.get("score"), dict) else {}
    v = score.get(key)
    try:
        return float(v)
    except Exception:
        return 0.0


def validate_report(report: Dict[str, Any]) -> Tuple[bool, str]:
    """
    Minimal schema validation (fail-fast but tolerant).
    """
    if not isinstance(report, dict):
        return False, "report_not_object"
    if "pass" not in report:
        return False, "missing_pass"
    if not isinstance(report.get("pass"), bool):
        return False, "pass_not_bool"
    # score is optional but recommended
    if "score" in report and not isinstance(report.get("score"), dict):
        return False, "score_not_object"
    if "issues" in report and not isinstance(report.get("issues"), list):
        return False, "issues_not_list"
    return True, "ok"


def apply_threshold_gate(
    report: Dict[str, Any],
    thresholds: EvaluatorThresholds,
    dims: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Mutates a shallow copy of report:
    - Ensures thresholds field
    - Enforces hard threshold(s) for each dimension
    - Computes overall if missing (best-effort weighted average)

    dims: optional scoring_dimensions override (from PipelineStageConfig)
    """
    dim_list = get_scoring_dimensions(dims)
    r = dict(report or {})
    r.setdefault("thresholds", thresholds.to_dict())

    # Hard thresholds: fail if any dimension below its minimum
    for d in dim_list:
        name = d["name"]
        min_val = thresholds.thresholds.get(name, 0.0)
        if min_val <= 0:
            continue
        dim_score = _get_score(r, name)
        if dim_score < min_val:
            if r.get("pass") is not False:
                r["pass"] = False
            r.setdefault("issues", [])
            try:
                issues = r.get("issues")
                if isinstance(issues, list):
                    issues.insert(
                        0,
                        {
                            "severity": "P0",
                            "title": f"未达{name}阈值",
                            "expected": f"{name} >= {min_val}",
                            "actual": f"{name} = {dim_score}",
                            "repro_steps": [],
                            "suggested_fix": f"补齐{name}相关指标后重新评估。",
                        },
                    )
            except Exception as e:
                logging.debug(str(e), exc_info=True)

    # Best-effort overall score using weighted average
    from .dimensions import compute_overall_score
    score = r.get("score") if isinstance(r.get("score"), dict) else {}
    if isinstance(score, dict) and "overall" not in score:
        score["overall"] = compute_overall_score(score, dims)
        r["score"] = score

    r.setdefault("evaluated_at", time.time())
    return r


async def persist_evaluation(
    *,
    execution_store: Any,
    run_id: str,
    trace_id: Optional[str],
    evaluator: str,
    report: Dict[str, Any],
    thresholds: EvaluatorThresholds,
    actor: Optional[Dict[str, Any]] = None,
    metadata_extra: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """
    Persist report as:
    - LearningArtifact(kind=evaluation_report, target_type=run)
    - run_event(type=evaluation_report)
    - audit_log(action=run_evaluation_submit)
    """
    mgr = LearningManager(execution_store=execution_store)
    version = f"eval:{int(time.time())}"
    meta = {"evaluator": evaluator, "thresholds": thresholds.to_dict(), "pass": bool(report.get("pass"))}
    if isinstance(metadata_extra, dict) and metadata_extra:
        meta.update(metadata_extra)
    art = await mgr.create_artifact(
        kind=LearningArtifactKind.EVALUATION_REPORT,
        target_type="run",
        target_id=str(run_id),
        version=version,
        status="draft",
        payload=report,
        metadata=meta,
        trace_id=str(trace_id) if trace_id else None,
        run_id=str(run_id),
    )
    # run event (best-effort)
    try:
        await execution_store.append_run_event(
            run_id=str(run_id),
            event_type="evaluation_report",
            trace_id=str(trace_id) if trace_id else None,
            tenant_id=(actor or {}).get("tenant_id") if isinstance(actor, dict) else None,
            payload={"artifact_id": art.artifact_id, "pass": bool(report.get("pass")), "evaluator": evaluator, "version": version},
        )
    except Exception as e:
        logging.debug(str(e), exc_info=True)
    # audit log (best-effort)
    try:
        if hasattr(execution_store, "add_audit_log") and isinstance(actor, dict):
            await execution_store.add_audit_log(
                action="run_evaluation_submit",
                status="ok",
                tenant_id=str(actor.get("tenant_id") or "") or None,
                actor_id=str(actor.get("actor_id") or "") or None,
                actor_role=str(actor.get("actor_role") or "") or None,
                resource_type="run",
                resource_id=str(run_id),
                detail={"artifact_id": art.artifact_id, "evaluator": evaluator, "pass": bool(report.get("pass"))},
            )
    except Exception as e:
        logging.debug(str(e), exc_info=True)

    # Regression → auto-rollback bridge: REJECTED + primary dimension < 5.0 triggers rollback
    try:
        if not report.get("pass") and report.get("recommendation") == "REJECTED":
            score = report.get("score") if isinstance(report.get("score"), dict) else {}
            dims = get_scoring_dimensions()
            primary_key = dims[0]["name"] if dims else "overall"
            if score.get(primary_key, 0) < 5.0:
                import os
                if os.getenv("AIPLAT_AUTO_ROLLBACK_ON_REGRESSION", "true").lower() not in ("0", "false", "no"):
                    from core.learning.autorollback import auto_rollback_regression
                    from core.harness.infrastructure.approval import ApprovalManager
                    await auto_rollback_regression(
                        store=execution_store,
                        approval_manager=ApprovalManager(),
                        agent_id=target_id or "",
                        min_samples=3,
                        error_rate_delta_threshold=0.2,
                        require_approval=False,
                    )
    except Exception as e:
        logging.debug(str(e), exc_info=True)

    return {"artifact_id": art.artifact_id, "version": version}
